class TestPlatformDetection(unittest.TestCase):
    def test_detects_one_of_three(self):
        self.assertIn(scheduler.system(), ("macos", "linux", "windows"))

    def test_every_platform_has_a_full_backend(self):
        """A platform missing an entry raises KeyError at install time, which
        is a crash rather than a message."""
        for plat in ("macos", "linux", "windows"):
            self.assertIn(plat, scheduler.BACKENDS)
            self.assertEqual(len(scheduler.BACKENDS[plat]), 5,
                             f"{plat} missing install/uninstall/status/start/stop")
            self.assertIn(plat, scheduler.TRAY_BACKENDS)

    def test_poller_and_tray_labels_differ(self):
        """They are separate agents with opposite lifecycles -- periodic versus
        resident. Sharing a label would make one clobber the other."""
        self.assertNotEqual(scheduler.LABEL, scheduler.TRAY_LABEL)

    def test_tray_label_is_not_a_prefix_collision(self):
        """`com.donnish.airo.tray` contains `com.donnish.airo`, which is how a
        substring match once reported the tray's pid as the poller's."""
        self.assertTrue(scheduler.TRAY_LABEL.startswith(scheduler.LABEL),
                        "if this stops being true the warning below is moot")
        src = (ROOT / "scheduler.py").read_text(encoding="utf-8")
        self.assertIn("parts[2] == LABEL", src,
                      "status must match the label exactly, not by substring")


class TestLaunchdPlist(unittest.TestCase):
    """macOS. Generated by writing a real plist to a temp path."""

    def build(self, interval=15, here=None, with_bundle=False):
        """Run the real macos_install() and read back what it wrote.

        It used to assemble the plist dict here and assert on that, which is a
        test of its own fixture: breaking macos_install so StartInterval held
        minutes instead of seconds -- a 60x error, polling every fifteen
        seconds -- left all five of these green. launchctl and getuid are
        stubbed so the macOS backend runs on every platform, which is also
        what makes these worth running in CI at all.
        """
        tmp = Path(tempfile.mkdtemp())
        path = tmp / f"{scheduler.LABEL}.plist"
        saved = (scheduler._plist_path, scheduler.run, scheduler._uid,
                 scheduler.HERE, scheduler.data_dir)
        scheduler._plist_path = lambda: path
        scheduler.run = lambda cmd, check=False: type(
            "R", (), {"returncode": 0, "stdout": "", "stderr": ""})()
        scheduler._uid = lambda: 501
        scheduler.data_dir = lambda: tmp / "data"
        # Which branch macos_install takes depended on whether an Airo.app
        # happened to be sitting in the developer's working tree, so the same
        # test meant different things on different machines -- and on the one
        # where a bundle existed, the argv branch was never exercised at all.
        # Made an input instead.
        scheduler.HERE = Path(here) if here is not None else tmp / "project"
        scheduler.HERE.mkdir(parents=True, exist_ok=True)
        if with_bundle:
            app = scheduler.HERE / "Airo.app" / "Contents" / "MacOS"
            app.mkdir(parents=True, exist_ok=True)
            (app / "Airo").write_text("#!/bin/sh\n", encoding="utf-8")
        try:
            ok, msg = scheduler.macos_install(interval)
            self.assertTrue(ok, msg)
            return plistlib.loads(path.read_bytes())
        finally:
            (scheduler._plist_path, scheduler.run, scheduler._uid,
             scheduler.HERE, scheduler.data_dir) = saved

    def test_uses_an_interval_not_keepalive(self):
        """ARCHITECTURE 2.1: the poller runs ~2s and exits. KeepAlive would
        make it resident for nothing, and a scheduler showing no pid between
        polls is correct rather than broken."""
        d = self.build()
        self.assertIn("StartInterval", d)
        self.assertNotIn("KeepAlive", d)

    def test_interval_is_in_seconds(self):
        self.assertEqual(self.build(15)["StartInterval"], 900)
        self.assertEqual(self.build(60)["StartInterval"], 3600)

    def test_working_directory_is_the_project(self):
        """Without it the agent runs from / and every relative path breaks --
        and poller.py --doctor uses it to tell whose agent this is.

        Compared against the project the plist was built *for*, not against
        scheduler.HERE read afterwards: the harness now points HERE at a
        temporary project so both bundle branches can be exercised, and
        reading the global back gave the real checkout instead.
        """
        import tempfile as tf
        here = Path(tf.mkdtemp()) / "My Project"
        self.assertEqual(str(here), self.build(here=here)["WorkingDirectory"])

    def test_absolute_paths_only(self):
        """launchd does not inherit a shell PATH."""
        for with_bundle in (False, True):
            with self.subTest(bundle=with_bundle):
                for arg in self.build(with_bundle=with_bundle)["ProgramArguments"]:
                    self.assertTrue(Path(arg).is_absolute() or arg.startswith("--"),
                                    f"not absolute: {arg}")

    def test_without_a_bundle_it_runs_the_poller_directly(self):
        argv = self.build(with_bundle=False)["ProgramArguments"]
        self.assertTrue(argv[-2].endswith("poller.py"), argv)
        self.assertEqual("--once", argv[-1])

    def test_with_a_bundle_it_runs_that_instead(self):
        """The .app exists so macOS attributes notifications and background
        activity to "Airo" rather than to "python3"."""
        argv = self.build(with_bundle=True)["ProgramArguments"]
        self.assertEqual(1, len(argv), argv)
        # Compared as path components: asserting the string
        # "Airo.app/Contents/MacOS/Airo" fails on Windows against a plist that
        # is entirely correct, because Path renders separators per platform.
        self.assertEqual(("Airo.app", "Contents", "MacOS", "Airo"),
                         Path(argv[0]).parts[-4:], argv)


class TestSystemdUnits(unittest.TestCase):
    """Linux. Generated into a temp directory, never enabled."""

    def build(self, interval=15):
        tmp = Path(tempfile.mkdtemp())
        saved = scheduler._systemd_dir
        scheduler._systemd_dir = lambda: tmp
        saved_which = scheduler.shutil.which
        scheduler.shutil.which = lambda name: None      # no systemctl: write only
        try:
            scheduler.linux_install(interval)
            return ((tmp / f"{scheduler.SERVICE_NAME}.service").read_text(encoding="utf-8"),
                    (tmp / f"{scheduler.SERVICE_NAME}.timer").read_text(encoding="utf-8"))
        finally:
            scheduler._systemd_dir = saved
            scheduler.shutil.which = saved_which

    def test_service_is_oneshot_not_a_daemon(self):
        service, _ = self.build()
        self.assertIn("Type=oneshot", service)

    def test_service_sets_a_working_directory(self):
        """Asserted after parsing rather than as a literal.

        This used to match the exact substring `WorkingDirectory=<path>`, so
        quoting the value -- which is what stops a path with a space breaking
        the unit -- broke a test about a unit that had just got *more*
        correct. A check pinned to formatting tests the formatting.
        """
        import shlex
        service, _ = self.build()
        line = [ln for ln in service.splitlines()
                if ln.startswith("WorkingDirectory=")][0]
        self.assertEqual([str(scheduler.HERE)],
                         shlex.split(line[len("WorkingDirectory="):]))

    def test_timer_cadence_matches_the_request(self):
        _, timer = self.build(20)
        self.assertIn("OnUnitActiveSec=20min", timer)

    def test_timer_recovers_a_poll_missed_while_asleep(self):
        """Persistent=true is the systemd equivalent of the gap backfill: a
        laptop that slept through a poll runs it on wake rather than skipping."""
        _, timer = self.build()
        self.assertIn("Persistent=true", timer)

    def test_timer_is_installable(self):
        _, timer = self.build()
        self.assertIn("[Install]", timer)
        self.assertIn("WantedBy=timers.target", timer)

    def test_units_are_written_even_without_systemctl(self):
        """A container or a minimal distro may lack systemctl. Writing the
        units and saying so beats failing silently."""
        ok, msg = None, None
        tmp = Path(tempfile.mkdtemp())
        saved, saved_which = scheduler._systemd_dir, scheduler.shutil.which
        scheduler._systemd_dir = lambda: tmp
        scheduler.shutil.which = lambda name: None
        try:
            ok, msg = scheduler.linux_install(15)
        finally:
            scheduler._systemd_dir, scheduler.shutil.which = saved, saved_which
        self.assertFalse(ok)
        self.assertIn("systemctl", msg)
        self.assertTrue((tmp / f"{scheduler.SERVICE_NAME}.timer").exists())


class TestWindowsTask(unittest.TestCase):
    """Windows. The schtasks argv is built and inspected, never run."""

    def capture(self, fn, *args):
        calls = []
        saved = scheduler.run
        scheduler.run = lambda cmd, check=False: (
            calls.append(cmd),
            type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})())[1]
        try:
            fn(*args)
        finally:
            scheduler.run = saved
        return calls

    def test_poller_task_uses_a_minute_interval(self):
        calls = self.capture(scheduler.windows_install, 15)
        cmd = calls[0]
        self.assertIn("/SC", cmd)
        self.assertEqual(cmd[cmd.index("/SC") + 1], "MINUTE")
        self.assertEqual(cmd[cmd.index("/MO") + 1], "15")

    def test_poller_task_is_forced_so_reinstall_works(self):
        self.assertIn("/F", self.capture(scheduler.windows_install, 15)[0])

    def test_tray_task_runs_at_logon_not_on_a_timer(self):
        """The tray is resident; scheduling it every N minutes would launch a
        second copy each time."""
        calls = self.capture(scheduler.windows_tray_install, "C:\\airo-tray.exe")
        cmd = calls[0]
        self.assertEqual(cmd[cmd.index("/SC") + 1], "ONLOGON")

    def test_poller_and_tray_use_different_task_names(self):
        poll = self.capture(scheduler.windows_install, 15)[0]
        tray = self.capture(scheduler.windows_tray_install, "x")[0]
        self.assertNotEqual(poll[poll.index("/TN") + 1],
                            tray[tray.index("/TN") + 1])


