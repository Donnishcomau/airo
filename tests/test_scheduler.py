class TestAPathWithASpaceDoesNotBreakTheSchedule(unittest.TestCase):
    """systemd splits `ExecStart=` on whitespace.

    A project folder called "My Air Quality" therefore produces
    `ExecStart=/usr/bin/python3 /home/me/My Air Quality/poller.py --once`,
    which systemd reads as five arguments. The units install cleanly, the timer
    enables, systemctl reports success -- and every poll fails with "No such
    file or directory". Nothing surfaces it: the failure is in the journal of a
    user unit nobody thinks to read, and the symptom is simply that no readings
    arrive.

    The other two backends were immune by accident rather than by design. A
    launchd plist holds ProgramArguments as an *array*, so the shell never sees
    it, and the schtasks command was already quoting its parts. Only the one
    that built a command by string interpolation was exposed -- which is the
    general lesson, not a fact about Linux.
    """

    SPACED = "/home/someone/My Air Quality"

    def build(self, here, interval=15, tray=False, binary=None):
        import shutil as real_shutil
        tmp = Path(tempfile.mkdtemp())
        saved = (scheduler.HERE, scheduler._systemd_dir, scheduler.shutil.which)
        scheduler.HERE = Path(here)
        scheduler._systemd_dir = lambda: tmp
        scheduler.shutil.which = lambda name: None
        try:
            if tray:
                scheduler.linux_tray_install(binary or f"{here}/airo-tray")
                name = f"{scheduler.TRAY_NAME}.service"
            else:
                scheduler.linux_install(interval)
                name = f"{scheduler.SERVICE_NAME}.service"
            return (tmp / name).read_text(encoding="utf-8")
        finally:
            (scheduler.HERE, scheduler._systemd_dir,
             scheduler.shutil.which) = saved

    def exec_line(self, unit):
        """The single ExecStart value in a unit.

        One return, and it asserts there is exactly one line rather than
        taking the first: systemd treats a second ExecStart in a oneshot
        service as an additional command, so a duplicate would run the poller
        twice per tick and neither line would look wrong on its own.
        """
        lines = [ln for ln in unit.splitlines() if ln.startswith("ExecStart=")]
        self.assertEqual(1, len(lines),
                         f"expected exactly one ExecStart in:\n{unit}")
        return lines[0][len("ExecStart="):]

    def systemd_argv(self, value):
        """Split an ExecStart value the way systemd does.

        Quoted arguments are one token; unquoted whitespace separates. Written
        out rather than trusted, because the whole bug was an assumption about
        this splitting.
        """
        import shlex
        # posix=True, because a systemd unit is a POSIX artefact whatever
        # platform generated it. Verified that it leaves Windows-style
        # backslashes intact rather than eating them as escapes.
        return shlex.split(value, posix=True)

    def test_the_poller_command_survives_a_space_in_the_path(self):
        argv = self.systemd_argv(self.exec_line(self.build(self.SPACED)))
        # Asserted as a property, not as a string. Comparing against a POSIX
        # path failed on the Windows runner against a unit that was correct:
        # Path renders separators for the platform it runs on, and these units
        # are generated there only as a test convenience. What matters is that
        # the path arrived as ONE argument with its space intact.
        self.assertEqual(3, len(argv), f"the command was split apart: {argv}")
        self.assertTrue(argv[1].endswith("poller.py"), argv)
        self.assertIn("My Air Quality", argv[1],
                      f"the space did not survive: {argv}")
        self.assertEqual("--once", argv[2])

    def test_the_tray_command_does_too(self):
        argv = self.systemd_argv(self.exec_line(self.build(self.SPACED, tray=True)))
        self.assertEqual(1, len(argv), f"the tray path was split apart: {argv}")
        self.assertIn("My Air Quality", argv[0])
        self.assertTrue(argv[0].endswith("airo-tray"), argv)

    def test_the_environment_the_tray_reads_survives_it(self):
        """AIRO_HOME tells the tray where the payload is. Split in half it
        points at a directory that does not exist, and the tray comes up with
        no data and no explanation."""
        unit = self.build(self.SPACED, tray=True)
        env = [ln for ln in unit.splitlines() if ln.startswith("Environment=")]
        home = [e for e in env if "AIRO_HOME" in e][0]
        value = home[len("Environment="):]
        tokens = self.systemd_argv(value)
        self.assertEqual(1, len(tokens), f"AIRO_HOME was split: {value}")
        self.assertTrue(tokens[0].startswith("AIRO_HOME="), tokens)
        self.assertIn("My Air Quality", tokens[0], tokens)

    def test_an_ordinary_path_is_unchanged_in_meaning(self):
        """The control. Quoting everything is only a fix if the common case
        still resolves to the same argv."""
        argv = self.systemd_argv(self.exec_line(self.build("/home/someone/airo")))
        self.assertEqual(3, len(argv), argv)
        self.assertTrue(argv[1].endswith("poller.py"), argv)
        self.assertEqual("--once", argv[2])

    def test_a_percent_in_the_path_is_not_read_as_a_specifier(self):
        """`%` introduces a systemd specifier: %h is the home directory, %n
        the unit name. An unescaped one in a path expands to something else
        entirely, which is a stranger failure to debug than a space."""
        unit = self.build("/home/someone/100%25 air")
        line = self.exec_line(unit)
        self.assertNotIn("%2", line.replace("%%", ""),
                         "a bare % survived into the unit file")


class SchedulerBackendCase(unittest.TestCase):
    """Run any platform's backend on any platform.

    Every one of these functions is a shell command away from being untestable,
    which is why two thirds of this module went uncovered: on Linux only the
    linux_* branches ran, on a Mac only the macos_*. Stubbing `run` and the
    handful of platform probes makes all three exercisable everywhere, and the
    thing being asserted -- *which command, with which arguments* -- is exactly
    where the bugs are.
    """

    def setUp(self):
        self.calls = []
        self.result = {"returncode": 0, "stdout": "", "stderr": ""}
        self.tmp = Path(tempfile.mkdtemp())
        self._saved = {name: getattr(scheduler, name) for name in
                       ("run", "_uid", "_plist_path", "_systemd_dir",
                        "data_dir", "HERE")}
        self._which = scheduler.shutil.which

        def fake_run(cmd, check=False):
            self.calls.append(list(cmd))
            return type("R", (), dict(self.result))()

        scheduler.run = fake_run
        scheduler._uid = lambda: 501
        scheduler._plist_path = lambda: self.tmp / "agent.plist"
        scheduler._systemd_dir = lambda: self.tmp / "systemd"
        scheduler.data_dir = lambda: self.tmp / "data"
        scheduler.HERE = self.tmp / "project"
        scheduler.HERE.mkdir(parents=True, exist_ok=True)
        scheduler.shutil.which = lambda name: f"/usr/bin/{name}"

    def tearDown(self):
        for name, value in self._saved.items():
            setattr(scheduler, name, value)
        scheduler.shutil.which = self._which

    def argv_containing(self, needle):
        return [c for c in self.calls if any(needle in str(a) for a in c)]


class TestEveryBackendStartsAndStops(SchedulerBackendCase):
    """start/stop had no tests on any platform. They are the two commands a
    user reaches for when something looks wrong, so a silent failure here is
    found at the worst possible moment."""

    LIFECYCLE = {
        "macos": (scheduler.macos_start, scheduler.macos_stop, "launchctl"),
        "linux": (scheduler.linux_start, scheduler.linux_stop, "systemctl"),
        "windows": (scheduler.windows_start, scheduler.windows_stop, "schtasks"),
    }

    INSTALLERS = {"macos": scheduler.macos_install,
                  "linux": scheduler.linux_install,
                  "windows": scheduler.windows_install}

    def test_each_platform_drives_its_own_scheduler(self):
        for plat, (start, _, tool) in self.LIFECYCLE.items():
            with self.subTest(platform=plat):
                self.INSTALLERS[plat](15)
                self.calls.clear()
                ok, msg = start()
                self.assertTrue(ok, msg)
                self.assertTrue(self.argv_containing(tool),
                                f"{plat} start ran {self.calls}")

    def test_starting_something_never_installed_says_so(self):
        """Rather than reporting success for a schedule that does not exist,
        which is how somebody ends up believing they are collecting data."""
        ok, msg = scheduler.macos_start()
        self.assertFalse(ok)
        self.assertIn("install", msg)

    def test_stopping_does_too(self):
        for plat, (_, stop, tool) in self.LIFECYCLE.items():
            with self.subTest(platform=plat):
                self.calls.clear()
                ok, msg = stop()
                self.assertTrue(ok, msg)
                self.assertTrue(self.argv_containing(tool))

    def test_a_failing_command_is_reported_not_swallowed(self):
        """Returning (True, ...) when the scheduler refused would tell someone
        their poller is running when it is not -- and the next thing they
        notice is a hole in the record."""
        for plat in self.LIFECYCLE:
            self.INSTALLERS[plat](15)
        self.result = {"returncode": 1, "stdout": "", "stderr": "denied"}
        for plat, (start, stop, _) in self.LIFECYCLE.items():
            for name, fn in (("start", start), ("stop", stop)):
                with self.subTest(platform=plat, action=name):
                    ok, msg = fn()
                    self.assertFalse(ok, f"{plat} {name} claimed success")
                    self.assertTrue(msg.strip(), "it failed without saying why")


class TestStatusReportsWhatIsActuallyRegistered(SchedulerBackendCase):

    def test_macos_matches_the_label_exactly(self):
        """`com.donnish.airo.tray` contains `com.donnish.airo`, so a loose
        match reports the tray's pid as the poller's -- and someone reads that
        as a healthy scheduler while nothing is collecting."""
        self.result = {"returncode": 0, "stderr": "",
                       "stdout": f"1234\t0\t{scheduler.LABEL}.tray\n"}
        ok, msg = scheduler.macos_status()
        self.assertFalse(ok, f"the tray was reported as the poller: {msg}")

        self.result["stdout"] = f"999\t0\t{scheduler.LABEL}\n"
        ok, msg = scheduler.macos_status()
        self.assertTrue(ok)
        self.assertIn("999", msg)

    def test_a_pid_of_dash_between_polls_is_still_registered(self):
        """The poller runs for about two seconds and exits. No pid between
        polls is correct, and reporting it as "not running" would send someone
        chasing a fault that is the design working."""
        self.result = {"returncode": 0, "stderr": "",
                       "stdout": f"-\t0\t{scheduler.LABEL}\n"}
        ok, _ = scheduler.macos_status()
        self.assertTrue(ok)

    def test_nothing_registered_says_so(self):
        self.result = {"returncode": 0, "stdout": "", "stderr": ""}
        for status in (scheduler.macos_status, scheduler.linux_status,
                       scheduler.windows_status):
            with self.subTest(status=status.__name__):
                ok, msg = status()
                self.assertIsInstance(ok, bool)
                self.assertTrue(msg.strip())


class TestUninstallRemovesWhatInstallWrote(SchedulerBackendCase):

    def test_linux_removes_both_units_and_says_which(self):
        scheduler.linux_install(15)
        d = scheduler._systemd_dir()
        self.assertTrue((d / f"{scheduler.SERVICE_NAME}.timer").exists())
        ok, msg = scheduler.linux_uninstall()
        self.assertTrue(ok)
        self.assertFalse((d / f"{scheduler.SERVICE_NAME}.timer").exists())
        self.assertFalse((d / f"{scheduler.SERVICE_NAME}.service").exists())
        self.assertIn("timer", msg)

    def test_linux_uninstall_with_nothing_installed_is_not_an_error(self):
        """Uninstalling twice, or on a machine where install never ran, is a
        thing people do. It must not look like a failure."""
        ok, msg = scheduler.linux_uninstall()
        self.assertTrue(ok)
        self.assertIn("nothing to remove", msg)

    def test_macos_removes_the_plist(self):
        scheduler.macos_install(15)
        self.assertTrue(scheduler._plist_path().exists())
        ok, _ = scheduler.macos_uninstall()
        self.assertTrue(ok)
        self.assertFalse(scheduler._plist_path().exists())

    def test_macos_uninstall_with_no_plist_is_not_an_error(self):
        ok, _ = scheduler.macos_uninstall()
