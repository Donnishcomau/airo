class TestTheCommandLineDispatch(SchedulerBackendCase):
    """`scheduler.py <action>` — the front door, and the least-covered part of
    the least-covered module.

    What it does is route an action to a backend and turn a (ok, message) pair
    into an exit code. Both halves matter to somebody running it from a
    terminal or a launchd job: a wrong route silently drives the wrong
    scheduler, and a wrong exit code makes a failed install look successful to
    anything checking `$?`.
    """

    #: Enumerated from the parser itself rather than written out here, so an
    #: action added later is in scope without anyone remembering. The listed
    #: version of this check is exactly how a project ends up with a command
    #: that has no test.
    def actions(self):
        import argparse
        for action in getattr(scheduler, "main").__doc__ or "":
            pass
        src = (ROOT / "scheduler.py").read_text(encoding="utf-8")
        import re
        m = re.search(r'choices=\((.*?)\)', src, re.S)
        self.assertTrue(m, "the action list has moved or changed shape")
        return re.findall(r'"([a-z-]+)"', m.group(1))

    def run_main(self, *argv):
        import contextlib
        import io
        out = io.StringIO()
        saved = sys.argv
        sys.argv = ["scheduler.py", *argv]
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
                code = scheduler.main()
        except SystemExit as e:
            code = e.code if isinstance(e.code, int) else 1
        finally:
            sys.argv = saved
        return code, out.getvalue()

    #: Which function each action must reach. The dispatch is an if/elif
    #: chain ending in a bare `else: status()`, so an action the chain does
    #: not handle does not fail -- it quietly reports status instead, and an
    #: install that never happened looks like a healthy one.
    ROUTES = {
        "install": "install", "uninstall": "uninstall", "start": "start",
        "stop": "stop", "restart": "restart", "status": "status",
        "install-tray": "install_tray", "uninstall-tray": "uninstall_tray",
    }

    def test_every_action_reaches_its_own_backend(self):
        """Asserted on which function ran, not on whether anything printed.

        The first version checked that each action "said something", which is
        true of a fall-through as well -- it passed with `uninstall-tray`
        routed to `status`.
        """
        actions = self.actions()
        self.assertEqual(sorted(self.ROUTES), sorted(actions),
                         "the parser's actions and this map have diverged")

        for action in actions:
            with self.subTest(action=action):
                ran = []
                saved = {}
                for name in set(self.ROUTES.values()):
                    saved[name] = getattr(scheduler, name)
                    setattr(scheduler, name, (
                        lambda n: lambda *a, **kw: (ran.append(n), (True, n))[1]
                    )(name))
                try:
                    code, said = self.run_main(action)
                finally:
                    for name, fn in saved.items():
                        setattr(scheduler, name, fn)
                self.assertEqual([self.ROUTES[action]], ran,
                                 f"{action} ran {ran} instead of "
                                 f"{self.ROUTES[action]}")
                self.assertEqual(0, code, said)

    def test_it_names_the_platform_it_is_acting_on(self):
        """Half the support questions about this file are somebody on one
        platform reading instructions for another."""
        _, said = self.run_main("status")
        self.assertIn(scheduler.system(), said)

    def test_a_failure_exits_nonzero(self):
        """launchd, systemd and Task Scheduler all read the exit code. An
        install that failed but exited 0 is recorded as healthy."""
        self.result = {"returncode": 1, "stdout": "", "stderr": "denied"}
        code, said = self.run_main("start")
        self.assertEqual(1, code, said)

    def test_success_exits_zero(self):
        for action in ("install", "start", "stop"):
            with self.subTest(action=action):
                self.INSTALLERS = None
                code, said = self.run_main(action)
                self.assertEqual(0, code, said)

    def test_the_interval_reaches_the_backend(self):
        """`--interval 30` that silently installs a 15-minute schedule is the
        kind of thing nobody notices for a month."""
        self.run_main("install", "--interval", "30")
        written = (self.tmp / "systemd" / f"{scheduler.SERVICE_NAME}.timer")
        plist = self.tmp / "agent.plist"
        if written.exists():
            self.assertIn("30min", written.read_text(encoding="utf-8"))
        elif plist.exists():
            import plistlib
            self.assertEqual(1800, plistlib.loads(plist.read_bytes())["StartInterval"])
        else:
            self.assertTrue(any("30" in " ".join(map(str, c)) for c in self.calls),
                            f"the interval never reached the backend: {self.calls}")

    def test_status_reports_the_tray_binary_or_how_to_build_it(self):
        """Status is diagnostic. "not built" with the command to fix it beats
        an empty line that reads as a missing feature."""
        _, said = self.run_main("status")
        self.assertTrue("tray binary:" in said, said)
        self.assertTrue("cargo build" in said or "/" in said.split("tray binary:")[1],
                        said)

    def test_an_unknown_action_is_refused_by_the_parser(self):
        """argparse exits 2 rather than falling through to status, which would
        report on a scheduler the user did not ask about."""
        code, _ = self.run_main("frobnicate")
        self.assertEqual(2, code)


class TestWhereTheDataDirComesFrom(unittest.TestCase):
    """Scheduler log paths must land beside the readings, not inside the
    project — or a migrated install writes its logs to a folder nothing else
    reads, and the person looking for them finds an empty file."""

    def test_it_asks_poller_rather_than_assuming(self):
        import poller
        self.assertEqual(Path(poller.DATA), scheduler.data_dir())

    def refuse_poller(self):
        """Run data_dir() with `import poller` broken. Returns (path, stderr)."""
        import builtins
        import contextlib
        import io
        import sys as _sys
        real_import = builtins.__import__

        def refuse(name, *a, **kw):
            if name == "poller":
                raise ImportError("poller is broken")
            return real_import(name, *a, **kw)

        saved = _sys.modules.pop("poller", None)
        builtins.__import__ = refuse
        err = io.StringIO()
        try:
            with contextlib.redirect_stderr(err):
                got = scheduler.data_dir()
        finally:
            builtins.__import__ = real_import
            if saved is not None:
                _sys.modules["poller"] = saved
        return got, err.getvalue()

    def test_it_falls_back_rather_than_raising_when_poller_cannot_load(self):
        """The fallback exists because scheduler.py has to work well enough to
        *uninstall* even when the rest of the project is broken -- which is
        exactly when somebody reaches for it."""
        got, _ = self.refuse_poller()
        self.assertIsInstance(got, Path)

    def test_the_fallback_is_the_real_default_not_the_project_folder(self):
        """It answered `$PROJECT/data`, which is the one path that is
        certainly wrong.

        CONVENTIONS rule 2a records that shape by name: hardcoding
        `$PROJECT/data` rather than asking poller created a stray empty
        database beside the real one and reported zero rows for a working
        install. Offering it as the *fallback* is the same mistake wearing a
        safety label -- a scheduler that cannot reach poller then writes its
        logs into the checkout, where nothing else looks.
        """
        got, _ = self.refuse_poller()
        self.assertNotEqual(scheduler.HERE / "data", got,
                            "the fallback still points inside the project")
        self.assertEqual(Path.home() / ".airo" / "data", got)

    def test_the_fallback_honours_AIRO_DATA_as_poller_does(self):
        elsewhere = Path(tempfile.gettempdir()) / "airo-fallback-probe"
        saved = os.environ.get("AIRO_DATA")
        os.environ["AIRO_DATA"] = str(elsewhere)
        try:
            got, _ = self.refuse_poller()
        finally:
            if saved is None:
                os.environ.pop("AIRO_DATA", None)
            else:
                os.environ["AIRO_DATA"] = saved
        self.assertEqual(elsewhere, got)

    def test_the_fallback_says_it_is_guessing(self):
        """A fallback that returns a plausible path in silence is how somebody
        spends an afternoon looking for logs that were written elsewhere."""
        got, said = self.refuse_poller()
        self.assertIn("poller", said)
        self.assertIn(str(got), said)


class TestATestCannotUninstallTheDevelopersAgent(unittest.TestCase):
    """The fourth route into the developer's own install, and the one that
    survived the first three being closed.

    `homeguard` redirects the paths and HOME. launchd cannot be redirected:
    `launchctl` addresses agents as `gui/<uid>/<label>`, keyed on the uid and
    a fixed label. So a subprocess running under a temp HOME deletes a plist
    that was never there and unloads the *real* agent belonging to the login
    session.

    This is how the developer's poller stopped. The evidence was unhelpful in
    every direction: the plists sat untouched on disk, `launchctl list` showed
    nothing, and the last line in the log is a clean successful poll. Nothing
    failed, so nothing was reported.
    """

    def redirect_home(self, to):
        """Redirect whichever variable this platform actually reads.

        Windows uses USERPROFILE, not HOME — a test setting only one runs
        against the real home directory on the other platform, which is a trap
        already written down in CONVENTIONS and one I walked into here.
        """
        for name in ("HOME", "USERPROFILE"):
            saved = os.environ.get(name)
            os.environ[name] = to
            self.addCleanup(
                lambda n=name, v=saved: os.environ.__setitem__(n, v) if v
                else os.environ.pop(n, None))

    def test_a_redirected_home_does_not_own_the_session(self):
        self.redirect_home(os.path.join(tempfile.gettempdir(), "not-a-home"))
        self.assertFalse(scheduler.owns_the_live_session())

    def test_the_real_home_does_own_it(self):
        """The other half. A guard that refuses everything protects nothing,
        because the first person it inconveniences turns it off.

        The real home comes from `homeguard`, which captured it at import
        before any redirection — asking the environment here would return the
        redirected one, since this whole suite runs under it. That the plain
        call above returns False during a test run *is the guard working*, and
        was the first result this test gave.
        """
        self.redirect_home(str(Path(REAL_AIRO_HOME).parent))
        self.assertTrue(scheduler.owns_the_live_session(),
                        "the ordinary case is being refused")

    def test_every_session_manager_is_guarded_not_just_launchd(self):
        """Enumerated from SESSION_MANAGERS rather than checked for launchctl
        alone. systemd's `--user` units and Task Scheduler are addressed the
        same way — by the session, not by HOME — so a Linux or Windows test
        doing what the macOS one did would have exactly the same effect there,
        and nobody would connect the two.
        """
        self.redirect_home(os.path.join(tempfile.gettempdir(), "not-a-home"))
        # Named literally, then enumerated. Enumerating alone was not enough:
        # narrowing SESSION_MANAGERS to ("launchctl",) shrank the loop with it
        # and nothing went red — "enumerate, don't list" protects against
        # something being *added* and missed, not against the enumeration
        # itself being cut. Which tools address a session is a claim about the
        # world, so it is written down; the behaviour is then checked over
        # whatever the module actually carries.
        for required in ("launchctl", "systemctl", "schtasks"):
            self.assertIn(required, scheduler.SESSION_MANAGERS,
                          f"{required} addresses the session by uid and is "
                          f"no longer guarded")
        for manager in scheduler.SESSION_MANAGERS:
            result = scheduler.run([manager, "--version"])
            self.assertEqual(1, result.returncode, manager)
            self.assertIn("logged-in session", result.stderr, manager)

    def test_an_ordinary_command_is_not_blocked_by_the_guard(self):
        """The guard is about sessions, not about subprocesses. Blocking
        everything under a redirected HOME would break the bundle tests, which
        legitimately run the shipped poller that way."""
        self.redirect_home(os.path.join(tempfile.gettempdir(), "not-a-home"))
        self.assertEqual(0, scheduler.run(["true"]).returncode)

    def test_the_guarded_runner_refuses_and_says_why(self):
        self.redirect_home(os.path.join(tempfile.gettempdir(), "not-a-home"))

        result = scheduler.run(["launchctl", "list"])
        self.assertNotEqual(0, result.returncode)
        self.assertIn("logged-in session", result.stderr,
                      "the refusal does not say what it refused or why")

    @unittest.skipUnless(hasattr(os, "getuid"),
                         "macos_stop() addresses launchd by uid, and Windows "
                         "has no getuid; the guard itself is covered on every "
                         "platform by the tests above")
    def test_uninstall_under_a_redirected_home_leaves_the_session_alone(self):
        """The end-to-end shape of it: the operation reports its failure
        rather than silently reaching across."""
        self.redirect_home(os.path.join(tempfile.gettempdir(), "not-a-home"))

        calls = []
        real = subprocess.run
        subprocess.run = lambda args, *a, **kw: (
            calls.append(args) or real(["true"], *a, **kw))
        self.addCleanup(lambda: setattr(subprocess, "run", real))

        scheduler.macos_stop()
        self.assertEqual(
            [], [c for c in calls if c and c[0] == "launchctl"],
            "launchctl reached a subprocess despite the redirected HOME")

    def test_no_session_manager_reaches_a_subprocess_from_this_suite(self):
        """The floor underneath the product's own guard, asserted rather than
        assumed.

        `scheduler.run()` refuses these while HOME is redirected, and every
        check above is about that refusal. This one goes around it: it calls
        `subprocess.run` directly, which is what a new suite does without
        meaning anything by it, and which no amount of care inside
        `scheduler.run` can cover.

        A guard nobody has watched fail is not evidence, so
        `tools/faults/guards.json` removes the installation and expects this to
        go red. `launchctl list` is a read, deliberately: while the guard is
        disabled the command really does run.
        """
        guard = schedguard.current()
        self.assertIsNotNone(guard, "the session guard is not installed")
        result = subprocess.run(["launchctl", "list"], capture_output=True,
                                text=True)
        self.assertEqual(1, result.returncode,
                         "a session manager reached a real subprocess")
        self.assertIn("logged-in session", result.stderr)
        self.assertTrue(guard.attempts, "the attempt was not recorded")

    def without_pwd(self):
        """Make `import pwd` fail, so the Windows branch runs on any machine.

        Both Windows behaviours below were green on macOS with the bug
        present, because `pwd` imports fine here and the fallback never ran.
        That is the shape this project keeps being caught by — a
        platform-specific symptom tested only on the platform that does not
        have it — and the stated remedy is to add a check that is not
        platform-specific. This is that check.
        """
        import builtins
        real_import = builtins.__import__

        def refuse(name, *args, **kwargs):
            if name == "pwd":
                raise ImportError("no pwd module on this platform")
            return real_import(name, *args, **kwargs)

        builtins.__import__ = refuse
        self.addCleanup(lambda: setattr(builtins, "__import__", real_import))

    def test_without_a_passwd_database_a_redirected_home_is_still_caught(self):
        """Windows has no passwd database, and `expanduser` reads the very
        variables under test, so it cannot be the reference. Returning True
        there was the first version, and it made the guard do nothing on the
        platform where Task Scheduler *is* the session manager — the exact
        failure this exists to prevent, on a different OS."""
        self.without_pwd()
        self.redirect_home(os.path.join(tempfile.gettempdir(), "not-a-home"))
        self.assertFalse(scheduler.owns_the_live_session())
        self.assertEqual(1, scheduler.run(["schtasks", "/query"]).returncode,
                         "Task Scheduler was reachable from a redirected home")

    def test_without_a_passwd_database_the_real_home_still_owns_it(self):
        self.without_pwd()
        self.redirect_home(str(scheduler._HOME_AT_IMPORT))
        self.assertTrue(scheduler.owns_the_live_session())

    def test_the_windows_variable_is_read_not_just_home(self):
        """`USERPROFILE`, not `HOME`. A test setting only one runs against the
        real home directory on the other platform — a trap already written
        down in CONVENTIONS, and one this guard walked into."""
        self.without_pwd()
        for name in ("HOME", "USERPROFILE"):
            saved = os.environ.get(name)
            os.environ.pop(name, None)
            self.addCleanup(
                lambda n=name, v=saved: os.environ.__setitem__(n, v) if v
                else os.environ.pop(n, None))
        os.environ["USERPROFILE"] = os.path.join(tempfile.gettempdir(),
                                                 "not-a-home")
        self.assertFalse(scheduler.owns_the_live_session(),
                         "USERPROFILE is ignored, so Windows is unguarded")


